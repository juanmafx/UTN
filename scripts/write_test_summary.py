import collections
import json
import pathlib
import platform
import sys
import xml.etree.ElementTree as ElementTree


def main():
    reports = pathlib.Path(sys.argv[1])
    java_version = sys.argv[2]
    suite = ElementTree.parse(reports / "java-tests.xml").getroot()
    database = json.loads((reports / "database-tests.json").read_text(encoding="utf-8"))
    per_suite = collections.defaultdict(lambda: [0, 0])
    for case in suite.findall("testcase"):
        name = case.get("classname").rsplit(".", 1)[1]
        per_suite[name][0] += 1
        per_suite[name][1] += 1 if case.find("failure") is not None else 0
    java_tests = int(suite.get("tests"))
    java_failed = int(suite.get("failures"))
    lines = [
        "# Test Report",
        "",
        "Generated by `scripts/test.sh` from an actual local run.",
        "",
        f"- Run timestamp (UTC): {suite.get('timestamp')}",
        f"- Java runtime: {java_version}",
        f"- Python: {platform.python_version()}",
        f"- Database engine: {database['engine']}",
        "",
        "| Suite | Tests | Passed | Failed |",
        "| --- | ---: | ---: | ---: |",
    ]
    for name in sorted(per_suite):
        total, failed = per_suite[name]
        lines.append(f"| {name} | {total} | {total - failed} | {failed} |")
    lines.append(f"| db/tests/test_schema.py | {database['tests']} | {database['passed']} | {database['failed']} |")
    total = java_tests + database["tests"]
    failed = java_failed + database["failed"]
    lines.append(f"| **Total** | **{total}** | **{total - failed}** | **{failed}** |")
    lines.extend(["", "Raw results: `java-tests.xml`, `database-tests.json`. Line coverage was not measured.", ""])
    (reports / "SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"total={total} passed={total - failed} failed={failed}")


if __name__ == "__main__":
    main()
